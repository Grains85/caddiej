"""What a camera is, as far as CaddieJ is concerned.

Not an object with frames on it. Nothing in CaddieJ ever holds a frame: the
camera is *described* here and the description is handed to FFmpeg, which is the
only thing that opens the device. So a camera is the arguments that name it plus
what it promises to deliver, and swapping a real camera for a synthetic one is
swapping one of these for another.

This is also why OpenCV is absent. `cv2.VideoCapture` would pull every frame into
Python, which cannot keep up at the frame rates a golf swing needs and reports
timestamps that vary by backend. OpenCV earns its place later, reading finished
clips off disk for analysis, never in the path that records them.
"""

from dataclasses import dataclass
from typing import Literal

CameraKind = Literal["synthetic", "avfoundation", "v4l2", "dshow"]


@dataclass(frozen=True, slots=True)
class CameraSpec:
    """One camera: how to open it, and what it claims to produce.

    `fps`, `width` and `height` are requested, not measured. A device that
    silently delivers something else is a real possibility, which is one more
    reason the recorded frame rate is written into a clip's metadata rather than
    assumed by whatever reads it later.
    """

    camera_id: str
    input_arguments: tuple[str, ...]
    fps: float
    width: int
    height: int
    latency_seconds: float = 0.0
    """How long after the light arrives the frame gets its timestamp.

    Exposure, transfer and encoding all sit in here, and it is device-specific
    and typically tens of milliseconds. Zero means "not measured", which is why
    clips default to `TimeQuality.ESTIMATED`.
    """

    description: str = ""

    def __post_init__(self) -> None:
        if not self.camera_id:
            raise ValueError("A camera needs an id")
        if self.fps <= 0:
            raise ValueError("A camera needs a positive frame rate")
        if self.width <= 0 or self.height <= 0:
            raise ValueError("A camera needs a positive frame size")


def synthetic_camera(
    camera_id: str = "synthetic",
    fps: float = 30.0,
    width: int = 1280,
    height: int = 720,
) -> CameraSpec:
    """A camera that is not there, generated by FFmpeg itself.

    This is the fake, and it is a real capture in every respect that matters:
    FFmpeg runs, segments land on disk, clips are cut from them. Only the
    photons are missing. It is what makes the whole pipeline runnable — and
    testable — on a machine with no camera attached.

    `-re` matters more than it looks. Without it a synthetic source is generated
    as fast as the CPU allows, so an hour of footage would appear in seconds and
    nothing about the rolling buffer would resemble reality.

    `testsrc2` draws a running timestamp into the picture on its own, without
    needing a text filter that a given FFmpeg build may not have been compiled
    with. That makes a clip self-describing: the frames say what time they are.
    """

    return CameraSpec(
        camera_id=camera_id,
        input_arguments=(
            "-re",
            "-f",
            "lavfi",
            "-i",
            f"testsrc2=size={width}x{height}:rate={_rate(fps)}",
        ),
        fps=fps,
        width=width,
        height=height,
        description="FFmpeg lavfi test pattern",
    )


def avfoundation_camera(
    device: str = "0",
    camera_id: str = "tee",
    fps: float = 30.0,
    width: int = 1280,
    height: int = 720,
    latency_seconds: float = 0.0,
) -> CameraSpec:
    """A macOS camera. `device` is an AVFoundation index or name."""

    return CameraSpec(
        camera_id=camera_id,
        input_arguments=(
            "-f",
            "avfoundation",
            "-framerate",
            _rate(fps),
            "-video_size",
            f"{width}x{height}",
            "-i",
            device,
        ),
        fps=fps,
        width=width,
        height=height,
        latency_seconds=latency_seconds,
        description=f"avfoundation:{device}",
    )


def v4l2_camera(
    device: str = "/dev/video0",
    camera_id: str = "tee",
    fps: float = 30.0,
    width: int = 1280,
    height: int = 720,
    latency_seconds: float = 0.0,
) -> CameraSpec:
    """A Linux camera."""

    return CameraSpec(
        camera_id=camera_id,
        input_arguments=(
            "-f",
            "v4l2",
            "-framerate",
            _rate(fps),
            "-video_size",
            f"{width}x{height}",
            "-i",
            device,
        ),
        fps=fps,
        width=width,
        height=height,
        latency_seconds=latency_seconds,
        description=f"v4l2:{device}",
    )


def dshow_camera(
    device: str,
    camera_id: str = "tee",
    fps: float = 30.0,
    width: int = 1280,
    height: int = 720,
    latency_seconds: float = 0.0,
) -> CameraSpec:
    """A Windows camera. `device` is the DirectShow friendly name.

    The name is one argument (`video=HD Pro Webcam`), so spaces are fine.
    A comma in the name is a DirectShow option separator and would need a
    different quoting form; that has not been exercised on hardware.
    """

    return CameraSpec(
        camera_id=camera_id,
        input_arguments=(
            "-f",
            "dshow",
            "-framerate",
            _rate(fps),
            "-video_size",
            f"{width}x{height}",
            "-i",
            f"video={device}",
        ),
        fps=fps,
        width=width,
        height=height,
        latency_seconds=latency_seconds,
        description=f"dshow:{device}",
    )


def build_camera(
    kind: CameraKind,
    device: str = "0",
    camera_id: str = "tee",
    fps: float = 30.0,
    width: int = 1280,
    height: int = 720,
    latency_seconds: float = 0.0,
) -> CameraSpec:
    """Pick a camera from configuration."""

    if kind == "synthetic":
        return synthetic_camera(
            camera_id=camera_id, fps=fps, width=width, height=height
        )
    builders = {
        "avfoundation": avfoundation_camera,
        "v4l2": v4l2_camera,
        "dshow": dshow_camera,
    }
    builder = builders.get(kind)
    if builder is None:
        raise ValueError(f"Unknown camera kind: {kind}")
    return builder(
        device=device,
        camera_id=camera_id,
        fps=fps,
        width=width,
        height=height,
        latency_seconds=latency_seconds,
    )


def _rate(fps: float) -> str:
    """Frame rates as FFmpeg prefers them: 30 rather than 30.0."""

    return str(int(fps)) if float(fps).is_integer() else str(fps)
